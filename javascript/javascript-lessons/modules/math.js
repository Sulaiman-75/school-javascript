//Modules are code blocks that can export & import variables, functions, objects, and classes
//Modules make code reusable, readable, prevent naming conflicts, organize code, and are easy to maintain and debug.
export function add(x, y) 
{
    return x + y;
}
export function subtract(x, y)
{
    return x - y;
}
export function multiply(x, y)
{
    return x * y;
}
export function divide(x, y)
{
    return x / y;
}
export const pi = 22/7;
